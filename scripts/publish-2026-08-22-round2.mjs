async function verifySource(record) {
  let lastResult;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const response = await fetch(record.source.url, {
        redirect: "follow",
        signal: AbortSignal.timeout(15000),
        headers: { "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/140 Safari/537.36" },
      });
      await response.body?.cancel();
      lastResult = {
        target: record.target,
        sourceUrl: record.source.url,
        finalUrl: response.url,
        status: response.status,
        ok: response.ok,
        checkedOn: today,
        attempts: attempt,
      };
      if (response.ok) return lastResult;
    } catch (error) {
      lastResult = {
        target: record.target,
        sourceUrl: record.source.url,
        finalUrl: record.source.url,
        status: 0,
        ok: false,
        checkedOn: today,
        attempts: attempt,
        error: error instanceof Error ? error.message : String(error),
      };
    }
    if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, attempt * 500));
  }
  return lastResult;
}

