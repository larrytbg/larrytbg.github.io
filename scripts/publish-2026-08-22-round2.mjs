function stripTags(value) {
  return value.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, " ").replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, " ").replace(/<sup\b[^>]*>[\s\S]*?<\/sup>/gi, " ").replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, " ").trim();
}

function escapeHtml(value) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#39;");
}

function replaceFirstParagraphInSection(html, sectionId, content) {
  const pattern = new RegExp(`(<section id="${sectionId}">[\\s\\S]*?<div class="sourced-paragraph"><p>)[\\s\\S]*?(</p>)`);
  return html.replace(pattern, `$1${content}$2`);
}

